export function translate(source: string): string {
  const bareSource = source.trim()
  const label = interfaceLabels[bareSource]
  if (label) return source.replace(bareSource, label[language.value === 'zh' ? 0 : language.value === 'ja' ? 1 : 2])
  if (language.value === 'zh') return source
  const index = language.value === 'ja' ? 0 : 1
  const exact = translations[bareSource]
  if (exact) return source.replace(bareSource, exact[index])
  if (bareSource.endsWith(' *')) return translate(source.slice(0, -2)) + ' *'
  if (!/[\u3400-\u9fff]/u.test(source)) return source
  const dynamicConfirmations: [RegExp, (...values: string[]) => [string, string]][] = [
    [/^查看(.+)的档案$/u, (name) => [`${name} のプロフィールを表示`, `View ${name}'s profile`]],
    [/^确认已收到进货单 (.+) 的全部商品并立即入库吗？$/u, (number) => [`発注 ${number} の全商品を受領し、在庫に追加しますか？`, `Confirm receipt of all items in order ${number} and add them to inventory?`]],
    [/^(.+) 已签收，库存和批次已更新$/u, (number) => [`${number} を受領しました。在庫とロットを更新しました`, `${number} received. Inventory and batches have been updated`]],
    [/^自动签收完成，共签收 (\d+) 张进货单$/u, (count) => [`自動受領が完了しました。${count} 枚の発注書を受領しました`, `Automatic receipt completed: ${count} purchase orders received`]],
    [/^确认废弃批次 (.+) 的全部剩余库存吗？$/u, (name) => [`ロット ${name} の残在庫をすべて廃棄しますか？`, `Discard all remaining stock in batch ${name}?`]],
    [/^确定要(停用|启用) (.+) 的账号吗？$/u, (action, name) => [`${name} のアカウントを${action === '停用' ? '無効' : '有効'}にしますか？`, `${action === '停用' ? 'Disable' : 'Enable'} ${name}'s account?`]],
    [/^确定重置 (.+) 的密码吗？$/u, (name) => [`${name} のパスワードをリセットしますか？`, `Reset ${name}'s password?`]],
    [/^确定删除折扣规则“(.+)”吗？关联商品也会一起移除。$/u, (name) => [`割引ルール「${name}」を削除しますか？対象商品も削除されます。`, `Delete discount rule “${name}” and its linked products?`]],
    [/^确定将“(.+)”移出当前折扣吗？$/u, (name) => [`「${name}」をこの割引から削除しますか？`, `Remove “${name}” from this discount?`]],
    [/^(开启|关闭)“(.+)”的理由（可不填）$/u, (action, name) => [`「${name}」を${action === '开启' ? '有効' : '無効'}にする理由（任意）`, `Reason to ${action === '开启' ? 'enable' : 'disable'} “${name}” (optional)`]],
  ]
  for (const [pattern, format] of dynamicConfirmations) {
    const match = source.match(pattern)
    if (match) return format(...match.slice(1))[index]
  }
  const standaloneUnits: Record<string, [string, string]> = {
    共: ['合計', 'Total'], 第: ['第', 'Page'], 至: ['〜', 'to'], 件: ['点', 'items'],
    批: ['ロット', 'batches'], 条: ['件', 'records'], 张: ['枚', 'orders'],
    单: ['件', 'orders'], 天: ['日', 'days'], 页: ['ページ', 'pages'],
    种: ['種類', 'types'], 点: ['点', 'items'],
  }
  const bare = source.trim()
  if (standaloneUnits[bare]) return source.replace(bare, standaloneUnits[bare][index])
  // 一次性按最长短语替换，避免已翻译的日语再次被其他词条改写。
  let result = source.replace(phrasePattern, (key) => translations[key]![index])
  result = result.replace(/第\s*(\d+)\s*\/\s*(\d+)\s*页/gu, (_, current: string, total: string) => {
    return index === 0 ? `${current} / ${total} ページ` : `Page ${current} of ${total}`
  })
  const units: Record<string, [string, string]> = {
    件: ['点', 'items'], 批: ['ロット', 'batches'], 条: ['件', 'records'],
    张: ['枚', 'orders'], 单: ['件', 'orders'], 天: ['日', 'days'], 页: ['ページ', 'pages'],
    种: ['種類', 'types'],
  }
  result = result.replace(/(\d+)\s*(件|批|条|张|单|天|页|种)(?![\u3400-\u9fff\u3040-\u30ff])/gu, (_, count: string, unit: string) => {
    return `${count} ${units[unit]![index]}`
  })
  result = result.replace(/共\s*(\d+)/gu, (_, count: string) => index === 0 ? `合計 ${count}` : `Total ${count}`)
  result = result.replace(/第\s*(\d+)/gu, (_, page: string) => index === 0 ? `第 ${page}` : `Page ${page}`)
  return result
}

export function confirmTranslated(message: string): boolean {
  return window.confirm(translate(message))
}

export function promptTranslated(message: string, defaultValue = ''): string | null {
  return window.prompt(translate(message), defaultValue)
}

function translateText(node: Text) {
  const current = node.nodeValue || ''
  let record = textSources.get(node)
  if (!record || (current !== record.last && current !== record.source)) {
    record = { source: current, last: current }
    textSources.set(node, record)
  }
  const next = translate(record.source)
  record.last = next
  if (current !== next) node.nodeValue = next
}

function translateElement(element: Element) {
  for (const attribute of translatableAttributes) {
    const current = element.getAttribute(attribute)
    if (current === null) continue
    let records = attributeSources.get(element)
    if (!records) {
      records = new Map()
      attributeSources.set(element, records)
    }
    let record = records.get(attribute)
    if (!record || (current !== record.last && current !== record.source)) {
      record = { source: current, last: current }
      records.set(attribute, record)
    }
    const next = translate(record.source)
    record.last = next
    if (current !== next) element.setAttribute(attribute, next)
  }
}

function translateTree(root: Node) {
  if (root.nodeType === Node.TEXT_NODE) {
    translateText(root as Text)
    return
  }
  if (!(root instanceof Element)) return
  if (root.closest('[data-no-translate]')) return
  translateElement(root)
  for (const child of root.childNodes) translateTree(child)
}

export function setLanguage(value: Language) {
  language.value = value
  localStorage.setItem('marketflow_language', value)
  document.documentElement.lang = value
  document.title = translate(originalPageTitle)
  translateTree(document.body)
}

export function setPageTitle(source: string) {
  originalPageTitle = source
  document.title = translate(source)
}

export function startTranslation() {
  document.documentElement.lang = language.value
  const root = document.body
  translateTree(root)
  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') translateTree(mutation.target)
      if (mutation.type === 'attributes') translateTree(mutation.target)
      for (const node of mutation.addedNodes) translateTree(node)
    }
  })
  observer.observe(root, {
    childList: true, subtree: true, characterData: true,
    attributes: true, attributeFilter: translatableAttributes,
  })
  return () => observer.disconnect()
}
